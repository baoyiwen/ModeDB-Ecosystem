/** Stable errors without OS paths, request payloads or secret material. */
export type SecurityErrorCode =
  | 'SECURITY_INVALID_CONFIG'
  | 'SECURITY_RATE_LIMITED'
  | 'SECURITY_TEMPORARILY_BANNED'
  | 'SECURITY_POLICY_CONFLICT'
  | 'SECURITY_CONFIRMATION_REQUIRED'
  | 'SECURITY_REAUTH_REQUIRED'
  | 'SECURITY_MAINTENANCE_FAILED'
  | 'SECURITY_SOURCE_DENIED'
  | 'SECURITY_ORIGIN_DENIED'
  | 'SECURITY_TLS_REQUIRED'
  | 'SECURITY_PROXY_UNTRUSTED'
  | 'SECURITY_CSRF_REQUIRED'
  | 'SECURITY_INVALID_REQUEST'
  | 'SECURITY_STORE_INVALID'
  | 'SECURITY_STORE_WRITE_FAILED'
  | 'SECURITY_INSTANCE_BUSY'
  | 'SECURITY_LOCAL_CHANNEL_UNAVAILABLE'
  | 'SECURITY_LOCAL_IDENTITY_DENIED'
  | 'SECURITY_CREDENTIAL_INVALID'
  | 'SECURITY_CREDENTIAL_EXPIRED'
  | 'SECURITY_CREDENTIAL_REVOKED'
  | 'SECURITY_NOT_FOUND'
  | 'SECURITY_AUDIT_CAPACITY'
  | 'SECURITY_RESPONSE_LIMIT'
  | 'SECURITY_FORBIDDEN'
  | 'SECURITY_RELEASE_SCOPE_CHANGED'
  | 'SECURITY_PROTOCOL_UNSUPPORTED'
  | 'SECURITY_OUTCOME_UNCONFIRMED'
  | 'SECURITY_CLOSED';

/** Errors safe for CLI and transport diagnostics. */
export class SecurityError extends Error {
  constructor(readonly code: SecurityErrorCode) {
    super(code);
    this.name = 'SecurityError';
  }
}
